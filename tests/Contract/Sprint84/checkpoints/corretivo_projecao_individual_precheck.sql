-- Sprint 8.4 / Microciclo 8.4.7-C / C2 / PRECHECK individual
-- Valores materializados para execução no SQL Developer:
--   ANO_EXECUCAO = 2027
--   UO_1 = 1 (planos 61/87/91; UASG 204)
--   UO_2 = 3 (planos 62/88/90; UASG 207)
--   LOGIN_SGI = jsilva
-- Execute cada SELECT separadamente e preserve a ordem apresentada.
-- Todas as consultas são somente leitura. Qualquer divergência bloqueia C3.

-- 01 estrategia_corrente
-- Colunas exatas: CHAVE_CONFIGURACAO, VALOR_CONFIGURACAO,
--                DESCRICAO_CONFIGURACAO
-- Cardinalidade: exatamente 1; chave ESTRATEGIA_PUBLICACAO_PLANOS e valor
-- INDIVIDUAL.
SELECT c.CHAVE AS CHAVE_CONFIGURACAO,
       c.VALOR AS VALOR_CONFIGURACAO,
       c.DESCRICAO AS DESCRICAO_CONFIGURACAO
  FROM SGI.PAC_CONFIGURACOES c
 WHERE c.CHAVE IN ('ESTRATEGIA_PUBLICACAO_PLANOS')
 ORDER BY c.CHAVE;

-- 02 representante
-- Colunas exatas: ID_REPRESENTANTE, NOME_REPRESENTANTE
-- Cardinalidade: exatamente 1 representante ativo; ID 709 para jsilva.
SELECT f.COD_FUNCIONARIO AS ID_REPRESENTANTE,
       f.NOME_CIVIL AS NOME_REPRESENTANTE
  FROM SGI.RH_FUNCIONARIOS f
 WHERE UPPER(f.NOME_USUARIO) = UPPER('jsilva')
   AND f.ATIVO = 1
 ORDER BY f.COD_FUNCIONARIO;

-- 03 lotacao_usuario
-- Colunas exatas: ID_LOTACAO, NOME_LOTACAO
-- Cardinalidade: exatamente 1 lotacao ativa e vinculo vigente; ID 1.
SELECT l.COD_LOTACAO AS ID_LOTACAO,
       l.NOME_LOTACAO AS NOME_LOTACAO
  FROM SGI.RH_FUNCIONARIOS f
  JOIN SGI.RH_FUNCIONARIOS_LOTACOES fl
    ON fl.COD_FUNCIONARIO = f.COD_FUNCIONARIO
  JOIN SGI.RH_LOTACOES l
    ON l.COD_LOTACAO = fl.COD_LOTACAO
 WHERE UPPER(f.NOME_USUARIO) = UPPER('jsilva')
   AND f.ATIVO = 1
   AND fl.DT_FIM_LOTACAO IS NULL
   AND l.ATIVO = 1
 ORDER BY l.COD_LOTACAO;

-- 04 unidades_orcamentarias
-- Colunas exatas: CHAVE_UO_PLANO, IDENTIDADE_UO, ID_LOTACAO,
--                DESCRICAO_LOTACAO, DESCRICAO_UO, CODIGO_UASG,
--                DESCRICAO_UASG
-- Cardinalidade: exatamente 2; UO fisica/identidade 1 com UASG 204 e UO
-- fisica/identidade 3 com UASG 207; UASGs preenchidas e distintas.
SELECT base.CHAVE_UO_PLANO,
       u.ID_UNIDADE_ORCAMENTARIA AS IDENTIDADE_UO,
       l.COD_LOTACAO AS ID_LOTACAO,
       l.NOME_LOTACAO AS DESCRICAO_LOTACAO,
       l.NOME_LOTACAO AS DESCRICAO_UO,
       u.CODIGO_UASG AS CODIGO_UASG,
       u.DESCRICAO_UASG AS DESCRICAO_UASG
  FROM (
        SELECT DISTINCT p.FK_UNIDADE_ORCAMENTARIA AS CHAVE_UO_PLANO
          FROM SGI.PAC_PLANOS p
         WHERE p.ANO_EXERCICIO = 2027
       ) base
  LEFT JOIN SGI.PAC_UNIDADES_ORCAMENTARIAS u
    ON u.ID_UNIDADE_ORCAMENTARIA = base.CHAVE_UO_PLANO
   AND u.ATIVA = 'S'
  LEFT JOIN SGI.RH_LOTACOES l
    ON l.COD_LOTACAO = u.ID_UNIDADE_ORCAMENTARIA
 ORDER BY base.CHAVE_UO_PLANO, u.ID_UNIDADE_ORCAMENTARIA;

-- 05 todas_versoes
-- Colunas exatas: ID_PLANO, FK_UNIDADE_ORCAMENTARIA, ANO_EXERCICIO, VERSAO,
--                DATA_HOMOLOGACAO, DATA_PUBLICACAO,
--                ESTRATEGIA_ADOTADA_PUBLICACAO, UASG_ADOTADA,
--                ESTADO_PUBLICACAO, SEQUENCIAL_PUBLICACAO_PNCP
-- Cardinalidade: exatamente 6; UO 1 = planos 61/87/91, versoes 1/2/3;
-- UO 3 = planos 62/88/90, versoes 1/2/3; todas homologadas.
-- Confirmadas: 61, 91, 62 e 90. Nao confirmadas: 87 e 88.
-- Estrategia/UASG em todas: INDIVIDUAL/204 na UO 1 e INDIVIDUAL/207 na UO 3.
-- Estado/sequencial: 61 = PUBLICADO/1; 62 = PUBLICADO/2; os pares dos planos
-- 87, 91, 88 e 90 devem estar integralmente nulos antes de C3.
SELECT p.ID_PLANO AS ID_PLANO,
       p.FK_UNIDADE_ORCAMENTARIA AS FK_UNIDADE_ORCAMENTARIA,
       p.ANO_EXERCICIO AS ANO_EXERCICIO,
       p.VERSAO AS VERSAO,
       TO_CHAR(p.DATA_HOMOLOGACAO, 'YYYY-MM-DD HH24:MI:SS') AS DATA_HOMOLOGACAO,
       TO_CHAR(p.DATA_PUBLICACAO, 'YYYY-MM-DD HH24:MI:SS') AS DATA_PUBLICACAO,
       p.ESTRATEGIA_ADOTADA_PUBLICACAO AS ESTRATEGIA_ADOTADA_PUBLICACAO,
       p.UASG_ADOTADA AS UASG_ADOTADA,
       p.ESTADO_PUBLICACAO AS ESTADO_PUBLICACAO,
       p.SEQUENCIAL_PUBLICACAO_PNCP AS SEQUENCIAL_PUBLICACAO_PNCP
  FROM SGI.PAC_PLANOS p
 WHERE p.ANO_EXERCICIO = 2027
   AND p.FK_UNIDADE_ORCAMENTARIA IN (1, 3)
 ORDER BY p.FK_UNIDADE_ORCAMENTARIA, p.VERSAO, p.ID_PLANO;

-- 06 versoes_vigentes
-- As mesmas 10 colunas exatas de todas_versoes.
-- Cardinalidade: exatamente 2; plano 91/UO 1/versao 3 e plano 90/UO 3/versao
-- 3; ambos homologados e confirmados. Estrategia/UASG devem estar preenchidas;
-- estado/sequencial devem estar integralmente nulos antes de C3.
SELECT p.ID_PLANO AS ID_PLANO,
       p.FK_UNIDADE_ORCAMENTARIA AS FK_UNIDADE_ORCAMENTARIA,
       p.ANO_EXERCICIO AS ANO_EXERCICIO,
       p.VERSAO AS VERSAO,
       TO_CHAR(p.DATA_HOMOLOGACAO, 'YYYY-MM-DD HH24:MI:SS') AS DATA_HOMOLOGACAO,
       TO_CHAR(p.DATA_PUBLICACAO, 'YYYY-MM-DD HH24:MI:SS') AS DATA_PUBLICACAO,
       p.ESTRATEGIA_ADOTADA_PUBLICACAO AS ESTRATEGIA_ADOTADA_PUBLICACAO,
       p.UASG_ADOTADA AS UASG_ADOTADA,
       p.ESTADO_PUBLICACAO AS ESTADO_PUBLICACAO,
       p.SEQUENCIAL_PUBLICACAO_PNCP AS SEQUENCIAL_PUBLICACAO_PNCP
  FROM SGI.PAC_PLANOS p
 WHERE p.ANO_EXERCICIO = 2027
   AND p.FK_UNIDADE_ORCAMENTARIA IN (1, 3)
   AND p.VERSAO = (
       SELECT MAX(pv.VERSAO)
         FROM SGI.PAC_PLANOS pv
        WHERE pv.ANO_EXERCICIO = p.ANO_EXERCICIO
          AND pv.FK_UNIDADE_ORCAMENTARIA = p.FK_UNIDADE_ORCAMENTARIA
   )
 ORDER BY p.FK_UNIDADE_ORCAMENTARIA, p.ID_PLANO;

-- 07 fotografia_vigente
-- Colunas exatas: ID_DEMANDA, SITUACAO, ID_UNIDADE_REQUISITANTE,
--                DATA_DESEJADA, CATEGORIA, DESCRICAO_DEMANDA,
--                UNIDADE_MEDIDA, QUANTIDADE, VALOR_TOTAL,
--                VALOR_ORCAMENTO_EXERCICIO, CATALOGO,
--                CLASSIFICACAO_CATALOGO, CODIGO_ITEM, GRUPO,
--                DESCRICAO_GRUPO, ORIGEM, FK_UNIDADE_ORCAMENTARIA
-- Cardinalidade: exatamente 5; UO 1 = IDs 800/807 e UO 3 = IDs 803/804/806.
-- CATALOGO = 2; CLASSIFICACAO_CATALOGO em (1, 2); SITUACAO em (2, 3, 5).
-- Todos os campos exigidos pelo payload devem estar preenchidos e validos.
SELECT d.ID_DEMANDA AS ID_DEMANDA,
       d.SITUACAO AS SITUACAO,
       d.FK_LOTACAO_AVALIADORA AS ID_UNIDADE_REQUISITANTE,
       TO_CHAR(d.DATA_COMPRA_CONTRATACAO, 'YYYY-MM-DD') AS DATA_DESEJADA,
       d.FK_CATEGORIA AS CATEGORIA,
       d.DESCRICAO_POPULAR_MATERIAL AS DESCRICAO_DEMANDA,
       d.UNIDADE_MEDIDA AS UNIDADE_MEDIDA,
       d.QUANTIDADE AS QUANTIDADE,
       TO_CHAR(d.VALOR_TOTAL, 'FM9999999999990D0000',
               'NLS_NUMERIC_CHARACTERS=''.,''') AS VALOR_TOTAL,
       TO_CHAR(d.VALOR_RESIDUAL_ANO, 'FM9999999999990D0000',
               'NLS_NUMERIC_CHARACTERS=''.,''') AS VALOR_ORCAMENTO_EXERCICIO,
       2 AS CATALOGO,
       d.CLASSIFICACAO_CATALOGO AS CLASSIFICACAO_CATALOGO,
       d.CODIGO_COMPLETO_MATERIAL AS CODIGO_ITEM,
       d.GRUPO_CODIGO AS GRUPO,
       mgm.DESCRICAO AS DESCRICAO_GRUPO,
       d.ORIGEM AS ORIGEM,
       origem.FK_UNIDADE_ORCAMENTARIA AS FK_UNIDADE_ORCAMENTARIA
  FROM SGI.PAC_DEMANDA d
  JOIN SGI.PAC_PLANOS origem
    ON origem.ID_PLANO = d.FK_PLANO
  LEFT JOIN CEBISIS.MT_GRUPOS_MATERIAIS@READ_ORCL mgm
    ON mgm.CODIGO = d.GRUPO_CODIGO
 WHERE origem.ANO_EXERCICIO = 2027
   AND origem.FK_UNIDADE_ORCAMENTARIA IN (1, 3)
   AND d.SITUACAO IN (2, 3, 5)
 ORDER BY origem.FK_UNIDADE_ORCAMENTARIA, d.ID_DEMANDA;

-- 08 ciclo_demandas
-- Colunas exatas: ID_DEMANDA, FK_PLANO, FK_UNIDADE_ORCAMENTARIA,
--                VERSAO_ORIGEM, SITUACAO
-- Cardinalidade: exatamente 7; UO 1 = IDs 800/801/807 e UO 3 =
-- IDs 802/803/804/806. Deve incluir as canceladas 801/802 e excluir a demanda
-- 805, cujo plano pertence ao exercicio 2026.
SELECT d.ID_DEMANDA AS ID_DEMANDA,
       d.FK_PLANO AS FK_PLANO,
       p.FK_UNIDADE_ORCAMENTARIA AS FK_UNIDADE_ORCAMENTARIA,
       p.VERSAO AS VERSAO_ORIGEM,
       d.SITUACAO AS SITUACAO
  FROM SGI.PAC_DEMANDA d
  JOIN SGI.PAC_PLANOS p
    ON p.ID_PLANO = d.FK_PLANO
 WHERE p.ANO_EXERCICIO = 2027
   AND p.FK_UNIDADE_ORCAMENTARIA IN (1, 3)
 ORDER BY p.FK_UNIDADE_ORCAMENTARIA, d.ID_DEMANDA;

-- 09 projecao_operacional
-- Colunas exatas: FK_UNIDADE_ORCAMENTARIA, VERSAO,
--                ESTRATEGIA_ADOTADA_PUBLICACAO, UASG_ADOTADA,
--                ESTADO_PUBLICACAO, SEQUENCIAL_PUBLICACAO_PNCP
-- Cardinalidade: exatamente 6. Estrategia/UASG devem estar preenchidas nas
-- seis linhas. UO 1: v1 PUBLICADO/1, v2-v3 nulas. UO 3: v1 PUBLICADO/2,
-- v2-v3 nulas. Nenhum par estado/sequencial pode estar parcialmente preenchido.
SELECT p.FK_UNIDADE_ORCAMENTARIA AS FK_UNIDADE_ORCAMENTARIA,
       p.VERSAO AS VERSAO,
       p.ESTRATEGIA_ADOTADA_PUBLICACAO AS ESTRATEGIA_ADOTADA_PUBLICACAO,
       p.UASG_ADOTADA AS UASG_ADOTADA,
       p.ESTADO_PUBLICACAO AS ESTADO_PUBLICACAO,
       p.SEQUENCIAL_PUBLICACAO_PNCP AS SEQUENCIAL_PUBLICACAO_PNCP
  FROM SGI.PAC_PLANOS p
 WHERE p.ANO_EXERCICIO = 2027
   AND p.FK_UNIDADE_ORCAMENTARIA IN (1, 3)
 ORDER BY p.FK_UNIDADE_ORCAMENTARIA, p.VERSAO, p.ID_PLANO;

-- 10 auditoria
-- Colunas exatas: DATA_REGISTRO, PROCEDIMENTO, MENSAGEM, FK_REPRESENTANTE,
--                FK_LOTACAO
-- Cardinalidade: exatamente 4; duas linhas do procedimento 5 e duas do
-- procedimento 8; todas para representante 709 e lotacao 1.
-- O UPPER em ambos os lados e obrigatorio para o Oracle configurado.
SELECT TO_CHAR(h.DATA_INSERCAO, 'YYYY-MM-DD HH24:MI:SS') AS DATA_REGISTRO,
       h.FK_PROCEDIMENTO AS PROCEDIMENTO,
       h.MENSAGEM AS MENSAGEM,
       h.FK_REPRESENTANTE AS FK_REPRESENTANTE,
       h.FK_LOTACAO AS FK_LOTACAO
  FROM SGI.PAC_HISTORICOS h
  JOIN SGI.RH_FUNCIONARIOS f
    ON f.COD_FUNCIONARIO = h.FK_REPRESENTANTE
 WHERE UPPER(f.NOME_USUARIO) = UPPER('jsilva')
   AND UPPER(h.MENSAGEM) LIKE UPPER('Exercício: 2027;%')
 ORDER BY h.DATA_INSERCAO, h.FK_PROCEDIMENTO, h.MENSAGEM;

-- 11 controles_concorrencia
-- Colunas exatas: ESCOPO, ANO_EXECUCAO, IDENTIFICADOR_ALVO
-- Cardinalidade: exatamente 3 ancoras permanentes, sem duplicidade:
-- ESTRATEGIA_ANUAL/2027/ESTRATEGIA_ANUAL,
-- UNIDADE_EXTERNA/2027/204 e UNIDADE_EXTERNA/2027/207.
SELECT c.ESCOPO AS ESCOPO,
       c.ANO_EXECUCAO AS ANO_EXECUCAO,
       c.IDENTIFICADOR_ALVO AS IDENTIFICADOR_ALVO
  FROM SGI.PAC_CONTROLES_CONCORRENCIA c
 WHERE c.ANO_EXECUCAO = 2027
 ORDER BY c.ESCOPO, c.IDENTIFICADOR_ALVO;
