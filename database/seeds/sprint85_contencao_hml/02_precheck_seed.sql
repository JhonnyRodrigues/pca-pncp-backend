-- Precheck bloqueante do seed minimo da contencao.
-- Execute cada SELECT separadamente. Nao prossiga se algum resultado divergir.

-- 01 ambiente: exatamente 1 linha; SGIHML / sgihml / SGI.
SELECT SYS_CONTEXT('USERENV', 'DB_NAME') AS DATABASE_NAME,
       SYS_CONTEXT('USERENV', 'SERVICE_NAME') AS SERVICE_NAME,
       SYS_CONTEXT('USERENV', 'CURRENT_SCHEMA') AS CURRENT_SCHEMA
  FROM DUAL;

-- 02 planos e demandas: exatamente 3 linhas, respectivamente
-- UO 3 = 3/3/3, UO 94 = 38/38/38 e UO 149 = 71/71/71.
SELECT p.FK_UNIDADE_ORCAMENTARIA,
       COUNT(DISTINCT p.ID_PLANO) AS PLANOS,
       COUNT(DISTINCT d.ID_DEMANDA) AS DEMANDAS,
       COUNT(DISTINCT CASE
           WHEN d.SITUACAO IN (2, 3, 5) THEN d.ID_DEMANDA
       END) AS DEMANDAS_ATIVAS
  FROM SGI.PAC_PLANOS p
  LEFT JOIN SGI.PAC_DEMANDA d
    ON d.FK_PLANO = p.ID_PLANO
 WHERE p.ANO_EXERCICIO = 2026
 GROUP BY p.FK_UNIDADE_ORCAMENTARIA
 ORDER BY p.FK_UNIDADE_ORCAMENTARIA;

-- 03 estado anterior: exatamente 1 linha com 112 em TOTAL_PLANOS e
-- PLANOS_SEM_ESTRATEGIA; os outros quatro valores devem ser zero.
SELECT COUNT(*) AS TOTAL_PLANOS,
       SUM(CASE
           WHEN p.ESTRATEGIA_ADOTADA_PUBLICACAO IS NULL
            AND p.UASG_ADOTADA IS NULL THEN 1 ELSE 0
       END) AS PLANOS_SEM_ESTRATEGIA,
       COUNT(p.ESTRATEGIA_ADOTADA_PUBLICACAO) AS PLANOS_COM_ESTRATEGIA,
       COUNT(p.UASG_ADOTADA) AS PLANOS_COM_UASG,
       COUNT(p.ESTADO_PUBLICACAO) AS PLANOS_COM_ESTADO,
       COUNT(p.SEQUENCIAL_PUBLICACAO_PNCP) AS PLANOS_COM_SEQUENCIAL
  FROM SGI.PAC_PLANOS p
 WHERE p.ANO_EXERCICIO = 2026;

-- 04 controles anteriores: exatamente 0 linhas.
SELECT c.ESCOPO,
       c.ANO_EXECUCAO,
       c.IDENTIFICADOR_ALVO
  FROM SGI.PAC_CONTROLES_CONCORRENCIA c
 WHERE c.ANO_EXECUCAO = 2026
 ORDER BY c.ESCOPO, c.IDENTIFICADOR_ALVO;

