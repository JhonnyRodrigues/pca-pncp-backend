-- Post-check do seed. Execute cada SELECT separadamente depois do script 03.

-- 01 projecao: exatamente 1 linha; TOTAL_PLANOS e CONFORMES devem ser 112,
-- e DIVERGENTES deve ser 0.
SELECT COUNT(*) AS TOTAL_PLANOS,
       SUM(CASE
           WHEN p.ESTRATEGIA_ADOTADA_PUBLICACAO = 'CONSOLIDADO'
            AND p.UASG_ADOTADA = '930281'
            AND p.ESTADO_PUBLICACAO IS NULL
            AND p.SEQUENCIAL_PUBLICACAO_PNCP IS NULL THEN 1 ELSE 0
       END) AS CONFORMES,
       SUM(CASE
           WHEN p.ESTRATEGIA_ADOTADA_PUBLICACAO = 'CONSOLIDADO'
            AND p.UASG_ADOTADA = '930281'
            AND p.ESTADO_PUBLICACAO IS NULL
            AND p.SEQUENCIAL_PUBLICACAO_PNCP IS NULL THEN 0 ELSE 1
       END) AS DIVERGENTES
  FROM SGI.PAC_PLANOS p
 WHERE p.ANO_EXERCICIO = 2026;

-- 02 controles: exatamente 2 linhas, com os dois valores abaixo.
SELECT c.ESCOPO,
       c.ANO_EXECUCAO,
       c.IDENTIFICADOR_ALVO
  FROM SGI.PAC_CONTROLES_CONCORRENCIA c
 WHERE c.ANO_EXECUCAO = 2026
 ORDER BY c.ESCOPO, c.IDENTIFICADOR_ALVO;

-- 03 massa preservada: exatamente 3 linhas: 3/3/3, 38/38/38 e 71/71/71.
SELECT p.FK_UNIDADE_ORCAMENTARIA,
       COUNT(DISTINCT p.ID_PLANO) AS PLANOS,
       COUNT(DISTINCT d.ID_DEMANDA) AS DEMANDAS,
       COUNT(DISTINCT CASE
           WHEN d.SITUACAO IN (2, 3, 5) THEN d.ID_DEMANDA
       END) AS DEMANDAS_ATIVAS
  FROM SGI.PAC_PLANOS p
  LEFT JOIN SGI.PAC_DEMANDA d
    ON d.FK_PLANO = p.ID_PLANO
 WHERE p.ANO_EXERCICIO = 2026
 GROUP BY p.FK_UNIDADE_ORCAMENTARIA
 ORDER BY p.FK_UNIDADE_ORCAMENTARIA;

