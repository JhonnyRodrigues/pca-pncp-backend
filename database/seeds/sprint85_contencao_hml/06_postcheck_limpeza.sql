-- Pos-check somente leitura da limpeza completa da massa da Sprint 8.5.
-- Execute cada SELECT separadamente depois de 05_limpar_seed.sql.

-- 01 ambiente: exatamente SGIHML / sgihml / SGI.
SELECT SYS_CONTEXT('USERENV', 'DB_NAME') AS DATABASE_NAME,
       SYS_CONTEXT('USERENV', 'SERVICE_NAME') AS SERVICE_NAME,
       SYS_CONTEXT('USERENV', 'CURRENT_SCHEMA') AS CURRENT_SCHEMA
  FROM DUAL;

-- 02 planos: TOTAL_PLANOS e SEM_ESTRATEGIA 112; demais valores zero.
SELECT COUNT(*) AS TOTAL_PLANOS,
       SUM(CASE
           WHEN p.ESTRATEGIA_ADOTADA_PUBLICACAO IS NULL
            AND p.UASG_ADOTADA IS NULL THEN 1 ELSE 0
       END) AS SEM_ESTRATEGIA,
       COUNT(p.ESTRATEGIA_ADOTADA_PUBLICACAO) AS COM_ESTRATEGIA,
       COUNT(p.UASG_ADOTADA) AS COM_UASG,
       COUNT(p.ESTADO_PUBLICACAO) AS COM_ESTADO,
       COUNT(p.SEQUENCIAL_PUBLICACAO_PNCP) AS COM_SEQUENCIAL,
       COUNT(p.DATA_PUBLICACAO) AS CONFIRMADOS
  FROM SGI.PAC_PLANOS p
 WHERE p.ANO_EXERCICIO = 2026;

-- 03 controles: zero linhas.
SELECT c.ESCOPO,
       c.ANO_EXECUCAO,
       c.IDENTIFICADOR_ALVO
  FROM SGI.PAC_CONTROLES_CONCORRENCIA c
 WHERE c.ANO_EXECUCAO = 2026
 ORDER BY c.ESCOPO, c.IDENTIFICADOR_ALVO;

-- 04 demandas: TOTAL 112, SITUACAO_2 106, SITUACAO_3 6 e OUTRAS 0.
SELECT COUNT(*) AS TOTAL_DEMANDAS,
       SUM(CASE WHEN d.SITUACAO = 2 THEN 1 ELSE 0 END) AS SITUACAO_2,
       SUM(CASE WHEN d.SITUACAO = 3 THEN 1 ELSE 0 END) AS SITUACAO_3,
       SUM(CASE
           WHEN d.SITUACAO NOT IN (2, 3) OR d.SITUACAO IS NULL THEN 1 ELSE 0
       END) AS OUTRAS_SITUACOES
  FROM SGI.PAC_DEMANDA d
  JOIN SGI.PAC_PLANOS p ON p.ID_PLANO = d.FK_PLANO
 WHERE p.ANO_EXERCICIO = 2026;

-- 05 plano intermediario: exatamente uma linha, sem confirmacao.
SELECT p.ID_PLANO,
       p.FK_UNIDADE_ORCAMENTARIA,
       p.VERSAO,
       TO_CHAR(p.DATA_PUBLICACAO, 'YYYY-MM-DD HH24:MI:SS') AS DATA_PUBLICACAO
  FROM SGI.PAC_PLANOS p
 WHERE p.ID_PLANO = 103
   AND p.ANO_EXERCICIO = 2026;

-- 06 auditoria de negocio: zero linhas.
SELECT h.FK_PROCEDIMENTO AS PROCEDIMENTO,
       h.MENSAGEM,
       h.FK_REPRESENTANTE,
       h.FK_LOTACAO
  FROM SGI.PAC_HISTORICOS h
  JOIN SGI.RH_FUNCIONARIOS f
    ON f.COD_FUNCIONARIO = h.FK_REPRESENTANTE
 WHERE UPPER(f.NOME_USUARIO) = UPPER('jsilva')
   AND UPPER(h.MENSAGEM) LIKE UPPER('Exercício: 2026;%');
