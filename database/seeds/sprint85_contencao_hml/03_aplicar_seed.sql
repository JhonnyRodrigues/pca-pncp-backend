-- Seed minimo e reversivel do gate de contencao da Sprint 8.5.
-- Ambiente permitido: somente SGIHML/sgihml.
-- Execute como script completo. Qualquer divergencia causa rollback.

DECLARE
    V_QUANTIDADE PLS_INTEGER;

    PROCEDURE EXIGIR(
        P_CONTEXTO IN VARCHAR2,
        P_ENCONTRADO IN PLS_INTEGER,
        P_ESPERADO IN PLS_INTEGER
    ) IS
    BEGIN
        IF P_ENCONTRADO <> P_ESPERADO THEN
            RAISE_APPLICATION_ERROR(
                -20851,
                'SPRINT85_SEED_RECUSADO: ' || P_CONTEXTO
                || ' esperava ' || P_ESPERADO
                || ' e encontrou ' || P_ENCONTRADO || '.'
            );
        END IF;
    END EXIGIR;
BEGIN
    IF SYS_CONTEXT('USERENV', 'DB_NAME') <> 'SGIHML'
       OR LOWER(SYS_CONTEXT('USERENV', 'SERVICE_NAME')) <> 'sgihml'
       OR SYS_CONTEXT('USERENV', 'CURRENT_SCHEMA') <> 'SGI'
    THEN
        RAISE_APPLICATION_ERROR(-20850, 'SPRINT85_SEED_RECUSADO: ambiente invalido.');
    END IF;

    SELECT COUNT(*)
      INTO V_QUANTIDADE
      FROM SGI.PAC_PLANOS p
     WHERE p.ANO_EXERCICIO = 2026;
    EXIGIR('total de planos', V_QUANTIDADE, 112);

    SELECT COUNT(*)
      INTO V_QUANTIDADE
      FROM SGI.PAC_PLANOS p
     WHERE p.ANO_EXERCICIO = 2026
       AND ((p.FK_UNIDADE_ORCAMENTARIA = 3)
         OR (p.FK_UNIDADE_ORCAMENTARIA = 94)
         OR (p.FK_UNIDADE_ORCAMENTARIA = 149));
    EXIGIR('planos das tres UOs', V_QUANTIDADE, 112);

    SELECT COUNT(*) INTO V_QUANTIDADE FROM SGI.PAC_PLANOS p
     WHERE p.ANO_EXERCICIO = 2026 AND p.FK_UNIDADE_ORCAMENTARIA = 3;
    EXIGIR('planos da UO 3', V_QUANTIDADE, 3);

    SELECT COUNT(*) INTO V_QUANTIDADE FROM SGI.PAC_PLANOS p
     WHERE p.ANO_EXERCICIO = 2026 AND p.FK_UNIDADE_ORCAMENTARIA = 94;
    EXIGIR('planos da UO 94', V_QUANTIDADE, 38);

    SELECT COUNT(*) INTO V_QUANTIDADE FROM SGI.PAC_PLANOS p
     WHERE p.ANO_EXERCICIO = 2026 AND p.FK_UNIDADE_ORCAMENTARIA = 149;
    EXIGIR('planos da UO 149', V_QUANTIDADE, 71);

    SELECT COUNT(*)
      INTO V_QUANTIDADE
      FROM SGI.PAC_PLANOS p
     WHERE p.ANO_EXERCICIO = 2026
       AND p.ESTRATEGIA_ADOTADA_PUBLICACAO IS NULL
       AND p.UASG_ADOTADA IS NULL
       AND p.ESTADO_PUBLICACAO IS NULL
       AND p.SEQUENCIAL_PUBLICACAO_PNCP IS NULL;
    EXIGIR('projecao operacional vazia', V_QUANTIDADE, 112);

    SELECT COUNT(*)
      INTO V_QUANTIDADE
      FROM SGI.PAC_DEMANDA d
      JOIN SGI.PAC_PLANOS p
        ON p.ID_PLANO = d.FK_PLANO
     WHERE p.ANO_EXERCICIO = 2026;
    EXIGIR('total de demandas', V_QUANTIDADE, 112);

    SELECT COUNT(*)
      INTO V_QUANTIDADE
      FROM SGI.PAC_DEMANDA d
      JOIN SGI.PAC_PLANOS p
        ON p.ID_PLANO = d.FK_PLANO
     WHERE p.ANO_EXERCICIO = 2026
       AND d.SITUACAO IN (2, 3, 5);
    EXIGIR('demandas ativas', V_QUANTIDADE, 112);

    SELECT COUNT(*) INTO V_QUANTIDADE
      FROM SGI.PAC_DEMANDA d JOIN SGI.PAC_PLANOS p ON p.ID_PLANO = d.FK_PLANO
     WHERE p.ANO_EXERCICIO = 2026 AND p.FK_UNIDADE_ORCAMENTARIA = 3
       AND d.SITUACAO IN (2, 3, 5);
    EXIGIR('demandas ativas da UO 3', V_QUANTIDADE, 3);

    SELECT COUNT(*) INTO V_QUANTIDADE
      FROM SGI.PAC_DEMANDA d JOIN SGI.PAC_PLANOS p ON p.ID_PLANO = d.FK_PLANO
     WHERE p.ANO_EXERCICIO = 2026 AND p.FK_UNIDADE_ORCAMENTARIA = 94
       AND d.SITUACAO IN (2, 3, 5);
    EXIGIR('demandas ativas da UO 94', V_QUANTIDADE, 38);

    SELECT COUNT(*) INTO V_QUANTIDADE
      FROM SGI.PAC_DEMANDA d JOIN SGI.PAC_PLANOS p ON p.ID_PLANO = d.FK_PLANO
     WHERE p.ANO_EXERCICIO = 2026 AND p.FK_UNIDADE_ORCAMENTARIA = 149
       AND d.SITUACAO IN (2, 3, 5);
    EXIGIR('demandas ativas da UO 149', V_QUANTIDADE, 71);

    SELECT COUNT(*)
      INTO V_QUANTIDADE
      FROM SGI.PAC_CONTROLES_CONCORRENCIA c
     WHERE c.ANO_EXECUCAO = 2026;
    EXIGIR('controles anteriores', V_QUANTIDADE, 0);

    UPDATE SGI.PAC_PLANOS p
       SET p.ESTRATEGIA_ADOTADA_PUBLICACAO = 'CONSOLIDADO',
           p.UASG_ADOTADA = '930281'
     WHERE p.ANO_EXERCICIO = 2026
       AND p.ESTRATEGIA_ADOTADA_PUBLICACAO IS NULL
       AND p.UASG_ADOTADA IS NULL
       AND p.ESTADO_PUBLICACAO IS NULL
       AND p.SEQUENCIAL_PUBLICACAO_PNCP IS NULL;
    EXIGIR('planos atualizados', SQL%ROWCOUNT, 112);

    INSERT INTO SGI.PAC_CONTROLES_CONCORRENCIA (
        ESCOPO,
        ANO_EXECUCAO,
        IDENTIFICADOR_ALVO
    ) VALUES (
        'ESTRATEGIA_ANUAL',
        2026,
        'ESTRATEGIA_ANUAL'
    );
    EXIGIR('controle da estrategia', SQL%ROWCOUNT, 1);

    INSERT INTO SGI.PAC_CONTROLES_CONCORRENCIA (
        ESCOPO,
        ANO_EXECUCAO,
        IDENTIFICADOR_ALVO
    ) VALUES (
        'UNIDADE_EXTERNA',
        2026,
        '930281'
    );
    EXIGIR('controle da unidade externa', SQL%ROWCOUNT, 1);

    SELECT COUNT(*)
      INTO V_QUANTIDADE
      FROM SGI.PAC_PLANOS p
     WHERE p.ANO_EXERCICIO = 2026
       AND p.ESTRATEGIA_ADOTADA_PUBLICACAO = 'CONSOLIDADO'
       AND p.UASG_ADOTADA = '930281'
       AND p.ESTADO_PUBLICACAO IS NULL
       AND p.SEQUENCIAL_PUBLICACAO_PNCP IS NULL;
    EXIGIR('projecao preparada', V_QUANTIDADE, 112);

    SELECT COUNT(*)
      INTO V_QUANTIDADE
      FROM SGI.PAC_CONTROLES_CONCORRENCIA c
     WHERE c.ANO_EXECUCAO = 2026
       AND ((c.ESCOPO = 'ESTRATEGIA_ANUAL'
             AND c.IDENTIFICADOR_ALVO = 'ESTRATEGIA_ANUAL')
         OR (c.ESCOPO = 'UNIDADE_EXTERNA'
             AND c.IDENTIFICADOR_ALVO = '930281'));
    EXIGIR('controles preparados', V_QUANTIDADE, 2);

    COMMIT;
EXCEPTION
    WHEN OTHERS THEN
        ROLLBACK;
        RAISE;
END;
