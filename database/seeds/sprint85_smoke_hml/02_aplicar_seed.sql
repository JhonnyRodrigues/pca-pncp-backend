-- Prepara o PCA consolidado excluido e a fotografia vazia do smoke.
-- Ambiente permitido: somente SGIHML/sgihml.

DECLARE
    V_QUANTIDADE PLS_INTEGER;

    PROCEDURE EXIGIR(
        P_CONTEXTO IN VARCHAR2,
        P_ENCONTRADO IN PLS_INTEGER,
        P_ESPERADO IN PLS_INTEGER
    ) IS
    BEGIN
        IF P_ENCONTRADO <> P_ESPERADO THEN
            RAISE_APPLICATION_ERROR(
                -20871,
                'SPRINT85_SMOKE_SEED_RECUSADO: ' || P_CONTEXTO
                || ' esperava ' || P_ESPERADO
                || ' e encontrou ' || P_ENCONTRADO || '.'
            );
        END IF;
    END EXIGIR;
BEGIN
    IF SYS_CONTEXT('USERENV', 'DB_NAME') <> 'SGIHML'
       OR LOWER(SYS_CONTEXT('USERENV', 'SERVICE_NAME')) <> 'sgihml'
       OR SYS_CONTEXT('USERENV', 'CURRENT_SCHEMA') <> 'SGI'
    THEN
        RAISE_APPLICATION_ERROR(-20870, 'SPRINT85_SMOKE_SEED_RECUSADO: ambiente invalido.');
    END IF;

    SELECT COUNT(*) INTO V_QUANTIDADE
      FROM SGI.PAC_PLANOS p
     WHERE p.ANO_EXERCICIO = 2026;
    EXIGIR('total de planos', V_QUANTIDADE, 112);

    SELECT COUNT(*) INTO V_QUANTIDADE
      FROM SGI.PAC_PLANOS p
     WHERE p.ANO_EXERCICIO = 2026
       AND p.ESTRATEGIA_ADOTADA_PUBLICACAO = 'CONSOLIDADO'
       AND p.UASG_ADOTADA = '930281'
       AND p.ESTADO_PUBLICACAO IS NULL
       AND p.SEQUENCIAL_PUBLICACAO_PNCP IS NULL
       AND p.DATA_PUBLICACAO IS NULL;
    EXIGIR('planos preparados e sem confirmacao', V_QUANTIDADE, 112);

    SELECT COUNT(*) INTO V_QUANTIDADE
      FROM SGI.PAC_DEMANDA d
      JOIN SGI.PAC_PLANOS p ON p.ID_PLANO = d.FK_PLANO
     WHERE p.ANO_EXERCICIO = 2026;
    EXIGIR('total de demandas', V_QUANTIDADE, 112);

    SELECT COUNT(*) INTO V_QUANTIDADE
      FROM SGI.PAC_DEMANDA d
      JOIN SGI.PAC_PLANOS p ON p.ID_PLANO = d.FK_PLANO
     WHERE p.ANO_EXERCICIO = 2026
       AND d.SITUACAO = 2;
    EXIGIR('demandas em situacao 2', V_QUANTIDADE, 106);

    SELECT COUNT(*) INTO V_QUANTIDADE
      FROM SGI.PAC_DEMANDA d
      JOIN SGI.PAC_PLANOS p ON p.ID_PLANO = d.FK_PLANO
     WHERE p.ANO_EXERCICIO = 2026
       AND d.SITUACAO = 3
       AND d.ID_DEMANDA IN (795, 799, 815, 824, 857, 867);
    EXIGIR('demandas conhecidas em situacao 3', V_QUANTIDADE, 6);

    SELECT COUNT(*) INTO V_QUANTIDADE
      FROM SGI.PAC_DEMANDA d
      JOIN SGI.PAC_PLANOS p ON p.ID_PLANO = d.FK_PLANO
     WHERE p.ANO_EXERCICIO = 2026
       AND (d.SITUACAO NOT IN (2, 3) OR d.SITUACAO IS NULL);
    EXIGIR('demandas em outras situacoes', V_QUANTIDADE, 0);

    SELECT COUNT(*) INTO V_QUANTIDADE
      FROM SGI.PAC_CONTROLES_CONCORRENCIA c
     WHERE c.ANO_EXECUCAO = 2026
       AND ((c.ESCOPO = 'ESTRATEGIA_ANUAL'
             AND c.IDENTIFICADOR_ALVO = 'ESTRATEGIA_ANUAL')
         OR (c.ESCOPO = 'UNIDADE_EXTERNA'
             AND c.IDENTIFICADOR_ALVO = '930281'));
    EXIGIR('controles esperados', V_QUANTIDADE, 2);

    SELECT COUNT(*) INTO V_QUANTIDADE
      FROM SGI.PAC_CONTROLES_CONCORRENCIA c
     WHERE c.ANO_EXECUCAO = 2026;
    EXIGIR('ausencia de controles adicionais', V_QUANTIDADE, 2);

    UPDATE SGI.PAC_DEMANDA d
       SET d.SITUACAO = 4
     WHERE d.SITUACAO IN (2, 3)
       AND EXISTS (
           SELECT 1
             FROM SGI.PAC_PLANOS p
            WHERE p.ID_PLANO = d.FK_PLANO
              AND p.ANO_EXERCICIO = 2026
       );
    EXIGIR('demandas retiradas da fotografia', SQL%ROWCOUNT, 112);

    UPDATE SGI.PAC_PLANOS p
       SET p.ESTADO_PUBLICACAO = 'EXCLUIDO',
           p.SEQUENCIAL_PUBLICACAO_PNCP = 36
     WHERE p.ANO_EXERCICIO = 2026
       AND p.ESTRATEGIA_ADOTADA_PUBLICACAO = 'CONSOLIDADO'
       AND p.UASG_ADOTADA = '930281'
       AND p.ESTADO_PUBLICACAO IS NULL
       AND p.SEQUENCIAL_PUBLICACAO_PNCP IS NULL
       AND p.DATA_PUBLICACAO IS NULL;
    EXIGIR('planos marcados como excluidos', SQL%ROWCOUNT, 112);

    SELECT COUNT(*) INTO V_QUANTIDADE
      FROM SGI.PAC_PLANOS p
     WHERE p.ANO_EXERCICIO = 2026
       AND p.ESTRATEGIA_ADOTADA_PUBLICACAO = 'CONSOLIDADO'
       AND p.UASG_ADOTADA = '930281'
       AND p.ESTADO_PUBLICACAO = 'EXCLUIDO'
       AND p.SEQUENCIAL_PUBLICACAO_PNCP = 36
       AND p.DATA_PUBLICACAO IS NULL;
    EXIGIR('projecao excluida preparada', V_QUANTIDADE, 112);

    SELECT COUNT(*) INTO V_QUANTIDADE
      FROM SGI.PAC_DEMANDA d
      JOIN SGI.PAC_PLANOS p ON p.ID_PLANO = d.FK_PLANO
     WHERE p.ANO_EXERCICIO = 2026
       AND d.SITUACAO = 4;
    EXIGIR('fotografia vazia preparada', V_QUANTIDADE, 112);

    COMMIT;
EXCEPTION
    WHEN OTHERS THEN
        ROLLBACK;
        RAISE;
END;
/
