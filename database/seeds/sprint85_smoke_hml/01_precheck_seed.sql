-- Precheck bloqueante da massa do smoke. Execute cada SELECT separadamente.

-- 01 ambiente: exatamente SGIHML / sgihml / SGI.
SELECT SYS_CONTEXT('USERENV', 'DB_NAME') AS DATABASE_NAME,
       SYS_CONTEXT('USERENV', 'SERVICE_NAME') AS SERVICE_NAME,
       SYS_CONTEXT('USERENV', 'CURRENT_SCHEMA') AS CURRENT_SCHEMA
  FROM DUAL;

-- 02 planos: uma linha; 112 em TOTAL e CONFORMES, zero em DIVERGENTES e
-- CONFIRMADOS.
SELECT COUNT(*) AS TOTAL_PLANOS,
       SUM(CASE
           WHEN p.ESTRATEGIA_ADOTADA_PUBLICACAO = 'CONSOLIDADO'
            AND p.UASG_ADOTADA = '930281'
            AND p.ESTADO_PUBLICACAO IS NULL
            AND p.SEQUENCIAL_PUBLICACAO_PNCP IS NULL THEN 1 ELSE 0
       END) AS CONFORMES,
       SUM(CASE
           WHEN p.ESTRATEGIA_ADOTADA_PUBLICACAO = 'CONSOLIDADO'
            AND p.UASG_ADOTADA = '930281'
            AND p.ESTADO_PUBLICACAO IS NULL
            AND p.SEQUENCIAL_PUBLICACAO_PNCP IS NULL THEN 0 ELSE 1
       END) AS DIVERGENTES,
       COUNT(p.DATA_PUBLICACAO) AS CONFIRMADOS
  FROM SGI.PAC_PLANOS p
 WHERE p.ANO_EXERCICIO = 2026;

-- 03 demandas: uma linha; TOTAL 112, SITUACAO_2 106, SITUACAO_3 6,
-- OUTRAS_SITUACOES 0.
SELECT COUNT(*) AS TOTAL_DEMANDAS,
       SUM(CASE WHEN d.SITUACAO = 2 THEN 1 ELSE 0 END) AS SITUACAO_2,
       SUM(CASE WHEN d.SITUACAO = 3 THEN 1 ELSE 0 END) AS SITUACAO_3,
       SUM(CASE WHEN d.SITUACAO NOT IN (2, 3) OR d.SITUACAO IS NULL
                THEN 1 ELSE 0 END) AS OUTRAS_SITUACOES
  FROM SGI.PAC_DEMANDA d
  JOIN SGI.PAC_PLANOS p
    ON p.ID_PLANO = d.FK_PLANO
 WHERE p.ANO_EXERCICIO = 2026;

-- 04 demandas em situacao 3: exatamente 6 linhas, IDs
-- 795, 799, 815, 824, 857 e 867.
SELECT d.ID_DEMANDA,
       d.FK_PLANO,
       p.FK_UNIDADE_ORCAMENTARIA,
       p.VERSAO,
       d.SITUACAO
  FROM SGI.PAC_DEMANDA d
  JOIN SGI.PAC_PLANOS p
    ON p.ID_PLANO = d.FK_PLANO
 WHERE p.ANO_EXERCICIO = 2026
   AND d.SITUACAO = 3
 ORDER BY d.ID_DEMANDA;

-- 05 versoes vigentes: exatamente 3 linhas, planos 143, 124 e 224, todas sem
-- confirmacao.
SELECT p.ID_PLANO,
       p.FK_UNIDADE_ORCAMENTARIA,
       p.VERSAO,
       TO_CHAR(p.DATA_PUBLICACAO, 'YYYY-MM-DD HH24:MI:SS') AS DATA_PUBLICACAO
  FROM SGI.PAC_PLANOS p
 WHERE p.ANO_EXERCICIO = 2026
   AND p.VERSAO = (
       SELECT MAX(pv.VERSAO)
         FROM SGI.PAC_PLANOS pv
        WHERE pv.ANO_EXERCICIO = p.ANO_EXERCICIO
          AND pv.FK_UNIDADE_ORCAMENTARIA = p.FK_UNIDADE_ORCAMENTARIA
   )
 ORDER BY p.FK_UNIDADE_ORCAMENTARIA;

-- 06 controles: exatamente as duas linhas já aprovadas.
SELECT c.ESCOPO,
       c.ANO_EXECUCAO,
       c.IDENTIFICADOR_ALVO
  FROM SGI.PAC_CONTROLES_CONCORRENCIA c
 WHERE c.ANO_EXECUCAO = 2026
 ORDER BY c.ESCOPO, c.IDENTIFICADOR_ALVO;

-- 07 auditoria de negocio: zero linhas.
SELECT h.FK_PROCEDIMENTO AS PROCEDIMENTO,
       h.MENSAGEM,
       h.FK_REPRESENTANTE,
       h.FK_LOTACAO
  FROM SGI.PAC_HISTORICOS h
  JOIN SGI.RH_FUNCIONARIOS f
    ON f.COD_FUNCIONARIO = h.FK_REPRESENTANTE
 WHERE UPPER(f.NOME_USUARIO) = UPPER('jsilva')
   AND UPPER(h.MENSAGEM) LIKE UPPER('Exercício: 2026;%');

-- 08 plano intermediario protegido: exatamente uma linha, plano 103 sem
-- confirmacao.
SELECT p.ID_PLANO,
       p.FK_UNIDADE_ORCAMENTARIA,
       p.VERSAO,
       TO_CHAR(p.DATA_PUBLICACAO, 'YYYY-MM-DD HH24:MI:SS') AS DATA_PUBLICACAO
  FROM SGI.PAC_PLANOS p
 WHERE p.ID_PLANO = 103
   AND p.ANO_EXERCICIO = 2026;
