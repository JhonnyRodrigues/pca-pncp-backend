-- Execute antes da migração V202609241700.
-- Cardinalidade: exatamente 2 linhas.
-- Estados aceitos: AUSENTE ou CONFORME.
-- Qualquer linha DIVERGENTE bloqueia a migração e exige análise.

WITH PROCEDIMENTO_ESPERADO AS (
    SELECT 8 AS ID_PROCEDIMENTO,
           'RETIFICAÇÃO DE PLANO' AS PROCEDIMENTO
      FROM DUAL
    UNION ALL
    SELECT 9 AS ID_PROCEDIMENTO,
           'EXCLUSÃO DE PLANO NO PNCP' AS PROCEDIMENTO
      FROM DUAL
),
PROCEDIMENTO_ENCONTRADO AS (
    SELECT E.ID_PROCEDIMENTO,
           E.PROCEDIMENTO,
           (
               SELECT MAX(P.PROCEDIMENTO)
                 FROM SGI.PAC_PROCEDIMENTOS P
                WHERE P.ID_PROCEDIMENTO = E.ID_PROCEDIMENTO
           ) AS NOME_POR_ID,
           (
               SELECT MAX(P.ID_PROCEDIMENTO)
                 FROM SGI.PAC_PROCEDIMENTOS P
                WHERE P.PROCEDIMENTO = E.PROCEDIMENTO
           ) AS ID_POR_NOME
      FROM PROCEDIMENTO_ESPERADO E
)
SELECT E.ID_PROCEDIMENTO AS ID_ESPERADO,
       E.PROCEDIMENTO AS NOME_ESPERADO,
       E.NOME_POR_ID AS NOME_ENCONTRADO_POR_ID,
       E.ID_POR_NOME AS ID_ENCONTRADO_POR_NOME,
       CASE
           WHEN E.NOME_POR_ID IS NULL AND E.ID_POR_NOME IS NULL
               THEN 'AUSENTE'
           WHEN E.NOME_POR_ID = E.PROCEDIMENTO
            AND E.ID_POR_NOME = E.ID_PROCEDIMENTO
               THEN 'CONFORME'
           ELSE 'DIVERGENTE'
       END AS SITUACAO
  FROM PROCEDIMENTO_ENCONTRADO E
 ORDER BY E.ID_PROCEDIMENTO;
