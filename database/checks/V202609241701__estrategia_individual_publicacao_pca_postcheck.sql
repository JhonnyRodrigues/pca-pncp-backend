-- Cardinalidade: exatamente 1 linha com SITUACAO = CONFORME.

WITH CONFIGURACAO_ESPERADA AS (
    SELECT 'INDIVIDUAL' AS VALOR,
           'Aceita os valores: INDIVIDUAL ou CONSOLIDADO. Define a estratégia operacional usada para publicar os planos no PNCP.' AS DESCRICAO
      FROM DUAL
)
SELECT 'ESTRATEGIA_PUBLICACAO_PLANOS' AS CHAVE_CONFIGURACAO,
       C.VALOR AS VALOR_ENCONTRADO,
       C.DESCRICAO AS DESCRICAO_ENCONTRADA,
       CASE
           WHEN C.CHAVE IS NOT NULL
            AND C.VALOR = E.VALOR
            AND C.DESCRICAO = E.DESCRICAO
               THEN 'CONFORME'
           ELSE 'DIVERGENTE'
       END AS SITUACAO
  FROM CONFIGURACAO_ESPERADA E
  LEFT JOIN SGI.PAC_CONFIGURACOES C
    ON C.CHAVE = 'ESTRATEGIA_PUBLICACAO_PLANOS';
